func TestIdentity(t *testing.T) {
	t.Parallel()
	guavaName, guava := pomProperties("com.google.guava", "guava", "33.2.0-jre")
	coreName, core := pomProperties("org.example", "demo-core", "1.0")
	demoName, demo := pomProperties("org.example", "demo", "1.0")

	for name, tc := range map[string]struct {
		file     string
		entries  map[string][]byte
		expected Identity
		shaded   int
	}{
		"a Maven artifact": {
			"guava-33.2.0-jre.jar",
			map[string][]byte{guavaName: guava, "META-INF/MANIFEST.MF": []byte("Bundle-Vendor: Google\n")},
			Identity{Group: "com.google.guava", Name: "guava", Version: "33.2.0-jre", Vendor: "Google", Source: SourcePOM},
			0,
		},
		"renamed: its one pom.properties is still its own": {
			"lib.jar",
			map[string][]byte{guavaName: guava},
			Identity{Group: "com.google.guava", Name: "guava", Version: "33.2.0-jre", Source: SourcePOM},
			0,
		},
		// The file is named after demo, and after demo-core less well.
		"several, one the file is named after": {
			"demo-1.0.jar",
			map[string][]byte{guavaName: guava, coreName: core, demoName: demo},
			Identity{Group: "org.example", Name: "demo", Version: "1.0", Source: SourcePOM},
			2,
		},
		"several, the longest name that fits": {
			"demo-core-1.0.jar",
			map[string][]byte{coreName: core, demoName: demo},
			Identity{Group: "org.example", Name: "demo-core", Version: "1.0", Source: SourcePOM},
			1,
		},
		"several, the file named after none: the manifest": {
			"service-all.jar",
			map[string][]byte{guavaName: guava, coreName: core, "META-INF/MANIFEST.MF": []byte("Implementation-Title: service\nImplementation-Version: 4.2\n")},
			Identity{Name: "service", Version: "4.2", Source: SourceManifest},
			2,
		},
		"an OSGi bundle": {
			"x.jar",
			map[string][]byte{"META-INF/MANIFEST.MF": []byte("Bundle-SymbolicName: org.example.bundle;singleton:=true\nBundle-Version: 2.1.0\nImplementation-Title: ignored\n")},
			Identity{Name: "org.example.bundle", Version: "2.1.0", Source: SourceManifest},
			0,
		},
		"a module name and no version": {
			"x.jar",
			map[string][]byte{"META-INF/MANIFEST.MF": []byte("Automatic-Module-Name: org.example.mod\n")},
			Identity{Name: "org.example.mod", Source: SourceManifest},
			0,
		},
		// The file name is all there is, and it is not taken apart for a
		// version.
		"nothing says: the file name": {
			"mystery-lib-2.0.jar",
			map[string][]byte{"A.class": []byte("x"), "META-INF/MANIFEST.MF": []byte("Manifest-Version: 1.0\n")},
			Identity{Name: "mystery-lib-2.0", Source: SourceFileName},
			0,
		},
		"a pom.properties missing a coordinate is none": {
			"odd.jar",
			map[string][]byte{"META-INF/maven/g/a/pom.properties": []byte("groupId=g\nartifactId=a\n")},
			Identity{Name: "odd", Source: SourceFileName},
			0,
		},
	} {
		archive := open(t, jar(t, tc.entries), tc.file)
		require.Equal(t, tc.expected, archive.Identity, name)
		require.Len(t, archive.Shaded, tc.shaded, name)
	}
}

type graph struct {
	root  *sbom.Node
	nodes map[string]*sbom.Node
	edges map[string]bool
}

func extract(t *testing.T, data []byte, name string) *graph {
	t.Helper()
	nl, err := New().ExtractArtifact(bytes.NewReader(data), name, &api.DecomposerOptions{})
	require.NoError(t, err)
	require.NotNil(t, nl)
	roots := nl.GetRootNodes()
	require.Len(t, roots, 1)

	g := &graph{root: roots[0], nodes: map[string]*sbom.Node{}, edges: map[string]bool{}}
	byID := map[string]*sbom.Node{}
	for _, node := range nl.GetNodes() {
		byID[node.GetId()] = node
		g.nodes[node.GetName()] = node
	}
	for _, e := range nl.GetEdges() {
		require.Equal(t, sbom.Edge_dependsOn, e.GetType())
		for _, to := range e.GetTo() {
			g.edges[byID[e.GetFrom()].GetName()+" -> "+byID[to].GetName()] = true
		}
	}
	return g
}

func properties(node *sbom.Node) map[string]string {
	out := map[string]string{}
	for _, property := range node.GetProperties() {
		out[property.GetName()] = property.GetData()
	}
	return out
}

// TestSpringBootJar reads an executable jar that carries its
// dependencies as archives inside it.
func TestSpringBootJar(t *testing.T) {
	t.Parallel()
	guava := library(t, "com.google.guava", "guava", "33.2.0-jre")
	slf4j := library(t, "org.slf4j", "slf4j-api", "2.0.13")
	appName, app := pomProperties("org.example", "shop", "1.4.0")
	data := jar(t, map[string][]byte{
		"META-INF/MANIFEST.MF":                   []byte("Manifest-Version: 1.0\nMain-Class: org.springframework.boot.loader.launch.JarLauncher\nImplementation-Vendor: Example Inc\n"),
		appName:                                  app,
		"BOOT-INF/classes/Shop.class":            []byte("shop"),
		"BOOT-INF/lib/guava-33.2.0-jre.jar":      guava,
		"BOOT-INF/lib/slf4j-api-2.0.13.jar":      slf4j,
		"BOOT-INF/lib/not-really.jar":            []byte("this is no zip"),
		"BOOT-INF/classes/static/readme.jar.txt": []byte("nor is this an archive"),
	})

	g := extract(t, data, "/app/shop.jar")
	require.Equal(t, "shop", g.root.GetName())
	require.Equal(t, "1.4.0", g.root.GetVersion())
	require.Equal(t, "pkg:maven/org.example/shop@1.4.0", string(g.root.Purl()))
	require.Equal(t, []sbom.Purpose{sbom.Purpose_APPLICATION}, g.root.GetPrimaryPurpose())
	require.Equal(t, "Example Inc", g.root.GetSuppliers()[0].GetName())
	require.Equal(t, map[string]string{
		PropertyIdentifiedBy: SourcePOM,
		PropertyMainClass:    "org.springframework.boot.loader.launch.JarLauncher",
	}, properties(g.root))
	require.Empty(t, g.root.GetHashes(), "the unpacker hashes the file it opened")

	require.Equal(t, map[string]bool{"shop -> guava": true, "shop -> slf4j-api": true}, g.edges)

	lib := g.nodes["guava"]
	require.Equal(t, "pkg:maven/com.google.guava/guava@33.2.0-jre", string(lib.Purl()))
	require.Equal(t, map[string]string{
		PropertyIdentifiedBy: SourcePOM,
		PropertyEmbedding:    EmbeddingNested,
		PropertyPath:         "BOOT-INF/lib/guava-33.2.0-jre.jar",
	}, properties(lib))
	// The hash is the nested file's.
	sum := sha256.Sum256(guava)
	require.Equal(t, hex.EncodeToString(sum[:]), lib.GetHashes()[int32(sbom.HashAlgorithm_SHA256)])
	require.Len(t, lib.GetHashes()[int32(sbom.HashAlgorithm_SHA1)], 40)
}

// TestEnterpriseArchive reads archives three deep, with one library in
// two of them.
func TestEnterpriseArchive(t *testing.T) {
	t.Parallel()
	shared := library(t, "org.apache.commons", "commons-lang3", "3.14.0")
	war := func(artifact string) []byte {
		name, content := pomProperties("org.example", artifact, "2.0")
		return jar(t, map[string][]byte{name: content, "WEB-INF/lib/commons-lang3-3.14.0.jar": shared, "WEB-INF/web.xml": []byte("<web-app/>")})
	}
	data := jar(t, map[string][]byte{
		"META-INF/MANIFEST.MF":         []byte("Implementation-Title: suite\nImplementation-Version: 2.0\n"),
		"store.war":                    war("store"),
		"admin.war":                    war("admin"),
		"lib/commons-lang3-3.14.0.jar": shared,
	})

	g := extract(t, data, "suite.ear")
	require.Equal(t, "suite", g.root.GetName())
	require.Equal(t, "pkg:generic/suite@2.0", string(g.root.Purl()))
	require.Equal(t, SourceManifest, properties(g.root)[PropertyIdentifiedBy])

	// The library is one node, bundled in the EAR and in both WARs.
	require.Len(t, g.nodes, 4)
	require.Equal(t, map[string]bool{
		"suite -> admin": true, "suite -> store": true, "suite -> commons-lang3": true,
		"admin -> commons-lang3": true, "store -> commons-lang3": true,
	}, g.edges)
}

// TestShadedJar reads a jar its dependencies were unpacked into.
func TestShadedJar(t *testing.T) {
	t.Parallel()
	guavaName, guava := pomProperties("com.google.guava", "guava", "33.2.0-jre")
	gsonName, gson := pomProperties("com.google.code.gson", "gson", "2.11.0")
	toolName, tool := pomProperties("org.example", "tool", "0.9")
	data := jar(t, map[string][]byte{guavaName: guava, gsonName: gson, toolName: tool, "Tool.class": []byte("x")})

	g := extract(t, data, "tool-0.9-shaded.jar")
	require.Equal(t, "pkg:maven/org.example/tool@0.9", string(g.root.Purl()))
	require.Equal(t, map[string]bool{"tool -> guava": true, "tool -> gson": true}, g.edges)
	require.Equal(t, map[string]string{
		PropertyIdentifiedBy: SourcePOM,
		PropertyEmbedding:    EmbeddingShaded,
	}, properties(g.nodes["gson"]))
	require.Empty(t, g.nodes["gson"].GetHashes(), "unpacked, it has no file to hash")
}

