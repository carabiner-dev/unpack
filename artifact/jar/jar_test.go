func TestMatches(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	d := New()
	for name, expected := range map[string]bool{
		"app.jar": true, "site.WAR": true, "suite.ear": true, "plugin.hpi": true,
		"archive.zip": false, "notes.jar.txt": false, "README": false,
	} {
		path := filepath.Join(dir, name)
		require.NoError(t, os.WriteFile(path, []byte("x"), 0o600))
		info, err := os.Stat(path)
		require.NoError(t, err)
		// A name is enough: an executable jar may open with a script.
		require.Equal(t, expected, d.Matches(info, []byte("#!/bin/sh")), name)
	}
	// With no name to go by, the magic number of a zip.
	require.True(t, d.Matches(nil, []byte("PK\x03\x04rest")))
	require.False(t, d.Matches(nil, []byte("\x7fELF")))
	require.False(t, d.Matches(nil, nil))
}

// plainReaderAt gives random access and says nothing of its size.
type plainReaderAt struct{ data []byte }

func (p plainReaderAt) ReadAt(b []byte, off int64) (int, error) {
	if off >= int64(len(p.data)) {
		return 0, io.EOF
	}
	n := copy(b, p.data[off:])
	if n < len(b) {
		return n, io.EOF
	}
	return n, nil
}

func TestExtractArtifact(t *testing.T) {
	t.Parallel()
	data := library(t, "org.example", "lib", "1.0")

	// Not a zip, whatever its name: disowned.
	nl, err := New().ExtractArtifact(bytes.NewReader([]byte("not an archive at all")), "fake.jar", nil)
	require.NoError(t, err)
	require.Nil(t, nl)

	// A reader that does not say how long it is is measured.
	for _, size := range []int{0, 1, 2, 3, 1000, 1023, 1024, 1025} {
		measured, err := sizeOf(plainReaderAt{make([]byte, size)})
		require.NoError(t, err)
		require.Equal(t, int64(size), measured)
	}
	nl, err = New().ExtractArtifact(plainReaderAt{data}, "lib-1.0.jar", nil)
	require.NoError(t, err)
	require.Equal(t, "lib", nl.GetRootNodes()[0].GetName())

	// A file on disk, through the plain entry point.
	path := filepath.Join(t.TempDir(), "lib-1.0.jar")
	require.NoError(t, os.WriteFile(path, data, 0o600))
	nl, err = New().Extract(&api.DecomposerOptions{WorkDir: path})
	require.NoError(t, err)
	require.Equal(t, "pkg:maven/org.example/lib@1.0", string(nl.GetRootNodes()[0].Purl()))

	_, err = New().Extract(&api.DecomposerOptions{})
	require.Error(t, err)
}
