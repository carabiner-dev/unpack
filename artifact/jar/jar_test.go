// The archives of the tests are built here and not kept as files: a jar
// in a repository is a binary nobody can read in a review.

// jar builds an archive from its entries, in the order of their names.
func jar(t *testing.T, entries map[string][]byte) []byte {
	t.Helper()
	names := make([]string, 0, len(entries))
	for name := range entries {
		names = append(names, name)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for _, name := range names {
		w, err := zw.Create(name)
		require.NoError(t, err)
		_, err = w.Write(entries[name])
		require.NoError(t, err)
	}
	require.NoError(t, zw.Close())
	return buf.Bytes()
}

func pomProperties(group, artifact, version string) (name string, content []byte) {
	return "META-INF/maven/" + group + "/" + artifact + "/pom.properties",
		[]byte("#Generated by Maven\n#Tue Jan 02 15:04:05 UTC 2026\ngroupId=" + group + "\nartifactId=" + artifact + "\nversion=" + version + "\n")
}

// library builds a plain library jar as Maven does.
func library(t *testing.T, group, artifact, version string) []byte {
	t.Helper()
	name, content := pomProperties(group, artifact, version)
	return jar(t, map[string][]byte{
		"META-INF/MANIFEST.MF": []byte("Manifest-Version: 1.0\r\nImplementation-Vendor: " + group + " project\r\n\r\n"),
		name:                   content,
		"Lib.class":            []byte(artifact),
	})
}

func open(t *testing.T, data []byte, name string) *Archive {
	t.Helper()
	zr, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	require.NoError(t, err)
	return readArchive(zr, name, 0)
}

